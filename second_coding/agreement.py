"""Agreement between the first coding (coding/failure_pattern_coding.csv plus
the reporting fields derived from its provenance) and the blind second coding.

Usage: python3 agreement.py coding_sheet_coder2.csv
Only claim_class is compared against the first coding directly; the three
yes/no fields are printed side by side for the reconciliation discussion.
"""
import os
import sys
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
FIRST = os.path.join(HERE, "..", "coding", "failure_pattern_coding.csv")


def cohen_kappa(a, b):
    cats = sorted(set(a) | set(b))
    n = len(a)
    po = sum(x == y for x, y in zip(a, b)) / n
    pe = sum((list(a).count(c) / n) * (list(b).count(c) / n) for c in cats)
    return float("nan") if pe == 1 else (po - pe) / (1 - pe)


first = pd.read_csv(FIRST)
first = first[first.import_status == "import"].set_index("paper_id")
second = pd.read_csv(sys.argv[1] if len(sys.argv) > 1 else "coding_sheet_coder2.csv",
                     dtype=str).set_index("paper_id")
missing = second.index[second.claim_class.isna()].tolist()
if missing:
    sys.exit(f"claim_class not filled for: {missing}")

ids = first.index.intersection(second.index)
a = first.loc[ids, "claim_class"].str.strip().str.lower().tolist()
b = second.loc[ids, "claim_class"].str.strip().str.lower().tolist()
agree = sum(x == y for x, y in zip(a, b))
print(f"claim_class: {agree}/{len(ids)} agree, Cohen's kappa = {cohen_kappa(a, b):.2f}")
for pid, x, y in zip(ids, a, b):
    if x != y:
        print(f"  DISAGREE {pid} ({first.loc[pid, 'ref']}): coder 1 = {x}, coder 2 = {y}")
print("\nCoder 2 yes/no fields (for discussion):")
print(second.loc[ids, ["classification_experiment", "baseline_comparison",
                       "significance_test", "claim_class"]].to_string())

# Macros for the manuscript (tables/coding_agreement.tex): written only when
# every claim_class has been filled, so the manuscript never shows a guess.
OUT_TEX = os.path.join(HERE, "..", "tables", "coding_agreement.tex")
os.makedirs(os.path.dirname(OUT_TEX), exist_ok=True)
with open(OUT_TEX, "w") as f:
    f.write("% AUTO-GENERATED by second_coding/agreement.py -- do not edit by hand.\n")
    f.write(f"\\newcommand{{\\CodingAgree}}{{{agree}}}\n")
    f.write(f"\\newcommand{{\\CodingTotal}}{{{len(ids)}}}\n")
    f.write(f"\\newcommand{{\\CodingKappa}}{{{cohen_kappa(a, b):.2f}}}\n")
    f.write(f"\\newcommand{{\\CodingDisagree}}{{{len(ids) - agree}}}\n")
print(f"\nwrote {OUT_TEX}")
